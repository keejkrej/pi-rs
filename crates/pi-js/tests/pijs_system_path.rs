#[test]
fn win32_cwd_functions_match_node() {
    let _cwd = CwdGuard::set(WIN_CWD);
    let _env = EnvGuard::set_many(&[("=D:", Some("D:\\dcwd")), ("=E:", Some("C:\\notE"))]);
    let mut failures = Vec::new();
    check_cwd(
        &WIN32,
        WIN32_RESOLVE_WCWD,
        WIN32_RELATIVE_WCWD,
        WIN32_NAMESPACED_WCWD,
        &mut failures,
    );
    finish(failures);
}

/// A posix-style cwd seen by `path.win32` and a Windows cwd seen by `path.posix` (what
/// Node does on a non-Windows host).
#[cfg(not(windows))]
#[test]
fn cross_platform_cwd_functions_match_node() {
    let mut failures = Vec::new();
    {
        let _cwd = CwdGuard::set(POSIX_CWD);
        let _env = EnvGuard::set_many(&[("=D:", None), ("=E:", None)]);
        check_cwd(
            &WIN32,
            WIN32_RESOLVE_PCWD,
            WIN32_RELATIVE_PCWD,
            WIN32_NAMESPACED_PCWD,
            &mut failures,
        );
    }
    {
        let _cwd = CwdGuard::set(WIN_CWD);
        check_cwd(
            &POSIX,
            POSIX_RESOLVE_WCWD,
            POSIX_RELATIVE_WCWD,
            POSIX_NAMESPACED_WCWD,
            &mut failures,
        );
    }
    finish(failures);
}

#[test]
fn constants_and_platform_default() {
    assert_eq!(posix::sep(), "/");
    assert_eq!(posix::delimiter(), ":");
    assert_eq!(win32::sep(), "\\");
    assert_eq!(win32::delimiter(), ";");
    if cfg!(windows) {
        assert_eq!(path::sep(), "\\");
        assert_eq!(path::delimiter(), ";");
        assert_eq!(path::join(&["a", "b"]), "a\\b");
    } else {
        assert_eq!(path::sep(), "/");
        assert_eq!(path::delimiter(), ":");
        assert_eq!(path::join(&["a", "b"]), "a/b");
        assert_eq!(path::basename("/x/y.ts", Some(".ts")), "y");
        assert_eq!(path::extname("/x/y.ts"), ".ts");
        assert!(path::is_absolute("/x"));
        assert_eq!(path::dirname("/x/y"), "/x");
        assert_eq!(path::normalize("/x/../y"), "/y");
        assert_eq!(path::relative("/a/b", "/a/c"), "../c");
        let _cwd = CwdGuard::set("/srv/app");
        assert_eq!(path::resolve(&["x"]), "/srv/app/x");
        assert_eq!(path::to_namespaced_path("x"), "x");
        assert_eq!(path::format(&path::parse("/a/b.c")), "/a/b.c");
    }
}

