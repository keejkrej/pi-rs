#[allow(clippy::type_complexity)]
struct Tables {
    normalize: &'static [(&'static str, &'static str)],
    is_absolute: &'static [(&'static str, bool)],
    dirname: &'static [(&'static str, &'static str)],
    extname: &'static [(&'static str, &'static str)],
    basename: &'static [(&'static str, Option<&'static str>, &'static str)],
    parse: &'static [(&'static str, [&'static str; 5])],
    format: &'static [([&'static str; 5], &'static str)],
    join: &'static [(&'static [&'static str], &'static str)],
}

fn check_pure(m: &Module, t: &Tables, failures: &mut Vec<String>) {
    for (p, want) in t.normalize {
        check("normalize", failures, p, (m.normalize)(p), want.to_string());
    }
    for (p, want) in t.is_absolute {
        check("isAbsolute", failures, p, (m.is_absolute)(p), *want);
    }
    for (p, want) in t.dirname {
        check("dirname", failures, p, (m.dirname)(p), want.to_string());
    }
    for (p, want) in t.extname {
        check("extname", failures, p, (m.extname)(p), want.to_string());
    }
    for (p, ext, want) in t.basename {
        check("basename", failures, (p, ext), (m.basename)(p, *ext), want.to_string());
    }
    for (p, want) in t.parse {
        check("parse", failures, p, (m.parse)(p), parsed(*want));
    }
    for (obj, want) in t.format {
        check("format", failures, obj, (m.format)(&parsed(*obj)), want.to_string());
    }
    for (args, want) in t.join {
        check("join", failures, args, (m.join)(args), want.to_string());
    }
}

#[allow(clippy::type_complexity)]
fn check_cwd(
    m: &Module,
    resolve: &[(&[&str], &str)],
    relative: &[(&str, &str, &str)],
    namespaced: &[(&str, &str)],
    failures: &mut Vec<String>,
) {
    for (args, want) in resolve {
        check("resolve", failures, args, (m.resolve)(args), want.to_string());
    }
    for (a, b, want) in relative {
        check("relative", failures, (a, b), (m.relative)(a, b), want.to_string());
    }
    for (p, want) in namespaced {
        check(
            "toNamespacedPath",
            failures,
            p,
            (m.to_namespaced_path)(p),
            want.to_string(),
        );
    }
}

#[test]
fn posix_pure_functions_match_node() {
    let mut failures = Vec::new();
    let t = Tables {
        normalize: POSIX_NORMALIZE,
        is_absolute: POSIX_IS_ABSOLUTE,
        dirname: POSIX_DIRNAME,
        extname: POSIX_EXTNAME,
        basename: POSIX_BASENAME,
        parse: POSIX_PARSE,
        format: POSIX_FORMAT,
        join: POSIX_JOIN,
    };
    check_pure(&POSIX, &t, &mut failures);
    finish(failures);
}

